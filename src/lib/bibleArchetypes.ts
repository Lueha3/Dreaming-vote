const byKey = new Map<string, BibleArchetype>();
for (const a of BIBLE_ARCHETYPES) {
  byKey.set(a.label, a);
  byKey.set(a.figure, a);
  byKey.set(a.label.replace(/형$/, ""), a);
}

/** label / figure / "이름"(형 생략) 어느 형태로 와도 아키타입을 찾는다. */
export function findArchetype(token: string): BibleArchetype | undefined {
  const t = token.trim();
  return byKey.get(t) ?? byKey.get(t.replace(/형$/, "")) ?? byKey.get(`${t}형`);
}

/**
 * coreTraits에서 '가장 닮은'(첫 번째로 인식되는) 아키타입 1개를 뽑는다.
 * coreTraits는 닮은 순으로 저장되므로 첫 매칭 토큰이 대표. 없으면 undefined.
 * 라인업 보드의 '대표 메달' 1개를 결정하는 데 쓴다.
 */
export function getPrimaryArchetype(coreTraits: string): BibleArchetype | undefined {
  for (const { archetype } of parseTraits(coreTraits)) {
    if (archetype) return archetype;
  }
  return undefined;
}

export type TraitToken = { token: string; archetype?: BibleArchetype };

/** coreTraits 문자열을 표시용 토큰으로 분해 (아키타입이면 매칭, 아니면 원문 유지). */
export function parseTraits(coreTraits: string): TraitToken[] {
  return coreTraits
    .split(/[,，、]/)
    .map((s) => s.trim())
    .filter(Boolean)
    .map((token) => ({ token, archetype: findArchetype(token) }));
}

/**
 * coreTraits를 정규화 — 인식된 아키타입은 canonical label로, 중복 제거.
 * 닮은 순서를 보존하되 최대 4개로 제한(약한 매치 컷). 닮은 만큼만 유동적으로 노출.
 * 하나도 인식 못하면(레거시·AI 미준수) 원문 그대로 반환해 데이터 보존.
 */
export function normalizeTraits(coreTraits: string): string {
  const labels = parseTraits(coreTraits)
    .map((t) => t.archetype?.label)
    .filter((l): l is string => Boolean(l));
  if (labels.length === 0) return coreTraits;
  return [...new Set(labels)].slice(0, 4).join(", ");
}

/**
 * 동아리 매칭 프롬프트용 — 아키타입 라벨을 키워드로 역확장해 의미 손실을 막는다.
 * "다윗형, 바울형" → "다윗형(전략·통찰·용기), 바울형(논리·사명·개척)"
 */
export function expandTraitsForMatching(coreTraits: string): string {
  return parseTraits(coreTraits)
    .map(({ token, archetype }) =>
      archetype ? `${archetype.label}(${archetype.keywords.join("·")})` : token,
    )
    .join(", ");
}

/** AI 프롬프트에 주입할 닫힌 목록 요약 (label + 유형 + 키워드). */
export function archetypeListForPrompt(): string {
  return BIBLE_ARCHETYPES.map(
    (a) => `- ${a.label}: ${a.type} (키워드: ${a.keywords.join(", ")})`,
  ).join("\n");
}
